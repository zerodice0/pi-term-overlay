import xterm from "@xterm/headless";
import type { IBufferCell, Terminal as XTerminal } from "@xterm/headless";
import { spawn, type IPty } from "zigpty";

const Terminal = xterm.Terminal;

// Standard xterm 16-color palette, used to answer OSC 4 palette queries.
const PALETTE = [
	"0000/0000/0000", "cdcd/0000/0000", "0000/cdcd/0000", "cdcd/cdcd/0000",
	"0000/0000/eeee", "cdcd/0000/cdcd", "0000/cdcd/cdcd", "e5e5/e5e5/e5e5",
	"7f7f/7f7f/7f7f", "ffff/0000/0000", "0000/ffff/0000", "ffff/ffff/0000",
	"5c5c/5c5c/ffff", "ffff/0000/ffff", "0000/ffff/ffff", "ffff/ffff/ffff",
];

export interface TermSessionOptions {
	name: string;
	file: string;
	args: string[];
	cwd: string;
	cols: number;
	rows: number;
	appearance: "dark" | "light";
	env?: Record<string, string>;
}

export class TermSession {
	readonly name: string;
	readonly cwd: string;
	readonly pid: number;
	readonly startedAt = Date.now();
	exited = false;
	exitCode: number | null = null;
	/** Bumped whenever the visible screen may have changed. */
	generation = 0;

	private readonly pty: IPty;
	private readonly term: XTerminal;
	private readonly renderListeners = new Set<() => void>();
	private readonly exitListeners = new Set<(code: number) => void>();
	private disposed = false;

	constructor(opts: TermSessionOptions) {
		this.name = opts.name;
		this.cwd = opts.cwd;
		const { cols, rows } = opts;
		this.term = new Terminal({ cols, rows, scrollback: 0, allowProposedApi: true });

		const env: Record<string, string> = {};
		for (const [k, v] of Object.entries({ ...process.env, ...opts.env })) {
			if (v !== undefined) env[k] = v;
		}
		env.TERM = "xterm-256color";
		env.COLORTERM = "truecolor";
		for (const k of ["TMUX", "TMUX_PANE", "COLUMNS", "LINES"]) delete env[k];

		this.pty = spawn(opts.file, opts.args, { name: "xterm-256color", cols, rows, cwd: opts.cwd, env });
		this.pid = this.pty.pid;

		// Replies generated by xterm itself (DA1, DSR/CPR, ...) go back to the app.
		this.term.onData((d) => this.write(d));

		const fg = opts.appearance === "light" ? "2020/2020/2020" : "d0d0/d0d0/d0d0";
		const bg = opts.appearance === "light" ? "ffff/ffff/ffff" : "1e1e/1e1e/1e1e";
		this.term.parser.registerOscHandler(10, (d) => (d === "?" && this.write(`\x1b]10;rgb:${fg}\x1b\\`), true));
		this.term.parser.registerOscHandler(11, (d) => (d === "?" && this.write(`\x1b]11;rgb:${bg}\x1b\\`), true));
		this.term.parser.registerOscHandler(4, (d) => {
			const parts = d.split(";");
			for (let i = 0; i + 1 < parts.length; i += 2) {
				const idx = Number(parts[i]);
				if (parts[i + 1] === "?" && PALETTE[idx]) this.write(`\x1b]4;${idx};rgb:${PALETTE[idx]}\x1b\\`);
			}
			return true;
		});
		// Window size in pixels (CSI 14 t); assume an 8x16 cell.
		this.term.parser.registerCsiHandler({ final: "t" }, (params) => {
			if (params[0] === 14) this.write(`\x1b[4;${this.term.rows * 16};${this.term.cols * 8}t`);
			else if (params[0] === 18) this.write(`\x1b[8;${this.term.rows};${this.term.cols}t`);
			return true;
		});

		this.pty.onData((data) => {
			if (this.disposed) return;
			this.term.write(typeof data === "string" ? data : data.toString("utf8"), () => {
				this.generation++;
				for (const l of this.renderListeners) l();
			});
		});
		this.pty.onExit(({ exitCode }) => {
			this.exited = true;
			this.exitCode = exitCode;
			for (const l of this.exitListeners) l(exitCode);
		});
	}

	get cols(): number {
		return this.term.cols;
	}
	get rows(): number {
		return this.term.rows;
	}
	get applicationCursorKeys(): boolean {
		return this.term.modes.applicationCursorKeysMode;
	}
	get bracketedPaste(): boolean {
		return this.term.modes.bracketedPasteMode;
	}

	onRender(fn: () => void): () => void {
		this.renderListeners.add(fn);
		return () => this.renderListeners.delete(fn);
	}

	onExit(fn: (code: number) => void): () => void {
		this.exitListeners.add(fn);
		return () => this.exitListeners.delete(fn);
	}

	write(data: string): void {
		if (this.exited || this.disposed || !data) return;
		try {
			this.pty.write(data);
		} catch {
			/* pty closed */
		}
	}

	resize(cols: number, rows: number): void {
		cols = Math.max(20, cols);
		rows = Math.max(5, rows);
		if (cols === this.term.cols && rows === this.term.rows) return;
		this.term.resize(cols, rows);
		if (!this.exited) {
			try {
				this.pty.resize(cols, rows);
			} catch {
				/* ignore */
			}
		}
		this.generation++;
	}

	kill(): void {
		if (!this.exited) {
			try {
				process.kill(-this.pid, "SIGHUP");
			} catch {
				/* not a group leader */
			}
			try {
				this.pty.kill("SIGHUP");
			} catch {
				/* ignore */
			}
		}
	}

	dispose(): void {
		if (this.disposed) return;
		this.kill();
		this.disposed = true;
		this.renderListeners.clear();
		this.exitListeners.clear();
		try {
			this.pty.close();
		} catch {
			/* ignore */
		}
		this.term.dispose();
	}

	/** Render the current viewport as ANSI lines, each exactly `cols` cells wide. */
	renderLines(): string[] {
		const buf = this.term.buffer.active;
		const cursorVisible = !isCursorHidden(this.term);
		const out: string[] = [];
		for (let y = 0; y < this.term.rows; y++) {
			const cursorX = cursorVisible && y === buf.cursorY ? buf.cursorX : -1;
			out.push(renderLine(this.term, buf.viewportY + y, cursorX));
		}
		return out;
	}
}

function isCursorHidden(term: XTerminal): boolean {
	try {
		// biome-ignore lint: private API, best effort only
		return Boolean((term as any)._core.coreService.isCursorHidden);
	} catch {
		return false;
	}
}

function colorSgr(isFg: boolean, cell: IBufferCell): string {
	if (isFg ? cell.isFgRGB() : cell.isBgRGB()) {
		const c = isFg ? cell.getFgColor() : cell.getBgColor();
		return `${isFg ? 38 : 48};2;${(c >> 16) & 255};${(c >> 8) & 255};${c & 255}`;
	}
	if (isFg ? cell.isFgPalette() : cell.isBgPalette()) {
		const c = isFg ? cell.getFgColor() : cell.getBgColor();
		if (c >= 0 && c < 256) return `${isFg ? 38 : 48};5;${c}`;
	}
	return "";
}

function renderLine(term: XTerminal, index: number, cursorX: number): string {
	const line = term.buffer.active.getLine(index);
	const cols = term.cols;
	let out = "\x1b[0m";
	let prev = "";
	const cell = term.buffer.active.getNullCell();
	for (let x = 0; x < cols; x++) {
		const c = line?.getCell(x, cell);
		if (!c) {
			if (prev !== "") {
				out += "\x1b[0m";
				prev = "";
			}
			out += x === cursorX ? "\x1b[7m \x1b[0m" : " ";
			continue;
		}
		const width = c.getWidth();
		if (width === 0) continue;
		const parts: string[] = [];
		if (c.isBold()) parts.push("1");
		if (c.isDim()) parts.push("2");
		if (c.isItalic()) parts.push("3");
		if (c.isUnderline()) parts.push("4");
		const inverse = Boolean(c.isInverse()) !== (x === cursorX);
		if (inverse) parts.push("7");
		if (c.isInvisible()) parts.push("8");
		if (c.isStrikethrough()) parts.push("9");
		const fg = colorSgr(true, c);
		const bg = colorSgr(false, c);
		if (fg) parts.push(fg);
		if (bg) parts.push(bg);
		const style = parts.join(";");
		if (style !== prev) {
			out += style ? `\x1b[0;${style}m` : "\x1b[0m";
			prev = style;
		}
		const chars = c.getChars();
		out += chars.length ? chars.replace(/[\x00-\x1f\x7f]/g, " ") : " ";
	}
	return `${out}\x1b[0m`;
}
